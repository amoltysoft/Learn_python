#--------- Arithmetic operator -----------
# additoin => +
# subtraction => -
# multiplition => *
# Division => /
# modulus => %
# exponent => **
# floor division => //


#EXMPLES
num1 = 7
num2 = 4
# addition
print (f"{num1}+{num2}={num1+num2}") # 11

# subtraction
print (f"{num1}-{num2}={num1-num2}") # 3

# multiplition
print (f"{num1}x{num2}={num1*num2}") # 28

# division 
print (f"{num1}÷{num2}={num1/num2}") # 1.75
# modulus 
print (f"{num1}%{num2}={num1%num2}") # 3
# exponent
print (f"{num1}**{num2}={num1**num2}") # 2401
# floor Division
print (f"{num1}//{num2}={num1//num2}") # 1

print (f"{num1}//{num2}={float(num1//num2)}") # 1.0
